"""Tables shared by the Rust importer.

They hold the literal patterns, block node families and reserved CrossGL identifiers, and the constant type,
semantic, stage, function and attribute maps. Each ``RustToCrossGLConverter`` instance copies the maps in
``__init__``, so per-instance changes stay local.
"""

