"""A position built-in on a vertex-stage input names an ordinary vertex attribute.

Direct3D matches a vertex shader's inputs to input-assembler elements by semantic name, and only
``SV_VertexID`` and ``SV_InstanceID`` are generated by the system there; DXC compiles a vertex input
``float4 p : SV_Position`` into the input signature with system value ``NONE`` (HLSL "Semantics",
System-Value Semantics). CrossGL reads ``@gl_Position``, ``@SV_Position`` and ``@builtin(position)`` as
the position built-in, which a vertex stage only writes, so GLSL declared the input without a location,
Metal put ``[[position]]`` in the ``[[stage_in]]`` structure (rejected by ``xcrun metal``), WGSL emitted
``@builtin(position)`` on a vertex input (rejected by naga) and SPIR-V read the ``gl_Position`` output.

:func:`attribute_vertex_input_positions` rewrites the attribute on a vertex entry point's inputs to the
``Position`` vertex attribute, the one HLSL's ``POSITION`` semantic imports as, for every target except
HLSL, which keeps the ``SV_Position`` input element. A structure that is also another entry point's output
or a non-vertex stage's input, an ``inout`` vertex entry parameter bound to the position built-in, and a
vertex input that already has a ``Position`` attribute, are refused with
:class:`VertexInputPositionUnsupportedError`, because one declaration cannot name both.
"""

from .. import ast as A
from ..diagnostics import CODE_PREFIX, TranslationDiagnostic
from .builtin_values import glsl_builtin_name
from .hub_types import iter_structs

__all__ = [
    "VertexInputPositionUnsupportedError",
    "attribute_vertex_input_positions",
]

POSITION_ATTRIBUTE = "Position"
_KEPT_TARGETS = frozenset(
    {"directx", "hlsl", "dx11", "dx12", "d3d11", "d3d12", "slang", "cgl", "crossgl"}
)


class VertexInputPositionUnsupportedError(TranslationDiagnostic):
    """A vertex input position that cannot become one vertex attribute."""

    def __init__(self, message, target):
        super().__init__(
            message,
            target=target,
            code=f"{CODE_PREFIX}vertex-input-position-unsupported",
        )


def attribute_vertex_input_positions(program, target) -> int:
    """Rewrite position built-ins on vertex inputs to the ``Position`` attribute; returns the count."""
    target = str(target or "").lower()
    if target in _KEPT_TARGETS or not isinstance(program, A.ShaderNode):
        return 0
    structs = {
        getattr(struct, "name", None): struct for struct in iter_structs(program)
    }
    vertex_inputs, other_uses = _struct_uses(program, structs)
    rewritten = 0
    for stage in _stages(program):
        if _stage_name(stage) != "vertex":
            continue
        entry = getattr(stage, "entry_point", None)
        parameters = getattr(entry, "parameters", None) or []
        for parameter in parameters:
            if _is_inout(parameter) and _position_index(parameter) is not None:
                raise VertexInputPositionUnsupportedError(
                    f"The inout parameter '{getattr(parameter, 'name', '')}' of vertex entry point "
                    f"'{getattr(entry, 'name', '')}' is the {POSITION_ATTRIBUTE} vertex attribute as an "
                    "input and the position built-in as an output",
                    target,
                )
        inputs = [
            parameter for parameter in parameters if _direction(parameter) == "input"
        ]
        inputs.extend(
            variable
            for variable in getattr(stage, "local_variables", None) or []
            if _direction(variable, default=None) == "input"
        )
        rewritten += _rewrite_inputs(
            inputs, f"vertex entry point '{getattr(entry, 'name', '')}'", target
        )
    for name in sorted(vertex_inputs):
        members = getattr(structs[name], "members", None) or []
        if not any(_position_index(member) is not None for member in members):
            continue
        if name in other_uses:
            raise VertexInputPositionUnsupportedError(
                f"Structure '{name}' is a vertex input whose position member is a vertex attribute, and "
                f"also {other_uses[name]}, where the same member is the position built-in",
                target,
            )
        rewritten += _rewrite_inputs(
            members, f"vertex input structure '{name}'", target
        )
    return rewritten


def _rewrite_inputs(inputs, context, target):
    positions = [node for node in inputs if _position_index(node) is not None]
    if not positions:
        return 0
    taken = [node for node in inputs if _has_position_attribute(node)]
    if taken or len(positions) > 1:
        names = ", ".join(
            f"'{getattr(node, 'name', '')}'" for node in positions + taken
        )
        raise VertexInputPositionUnsupportedError(
            f"The inputs {names} of {context} would all be the {POSITION_ATTRIBUTE} vertex attribute",
            target,
        )
    node = positions[0]
    node.attributes[_position_index(node)] = A.AttributeNode(POSITION_ATTRIBUTE, [])
    return 1


def _position_index(node):
    for index, attribute in enumerate(getattr(node, "attributes", None) or []):
        if str(glsl_builtin_name(attribute) or "").lower() == "gl_position":
            return index
    return None


def _has_position_attribute(node):
    return any(
        str(getattr(attribute, "name", "") or "").lower() in {"position", "position0"}
        for attribute in getattr(node, "attributes", None) or []
    )


def _struct_uses(program, structs):
    """Structures a vertex entry point takes as inputs, and every other entry-point use of a structure."""
    vertex_inputs = set()
    other_uses = {}

    def note_other(type_node, use):
        name = _type_name(type_node)
        if name in structs:
            other_uses.setdefault(name, use)

    for stage in _stages(program):
        entry = getattr(stage, "entry_point", None)
        if entry is None:
            continue
        stage_name = _stage_name(stage)
        entry_name = getattr(entry, "name", "")
        note_other(
            getattr(entry, "return_type", None),
            f"the {stage_name} entry point '{entry_name}' output",
        )
        for parameter in getattr(entry, "parameters", None) or []:
            name = _type_name(getattr(parameter, "param_type", None))
            if name not in structs:
                continue
            direction = _direction(parameter)
            if stage_name == "vertex" and direction == "input":
                vertex_inputs.add(name)
            elif direction == "input":
                note_other(
                    parameter.param_type,
                    f"the {stage_name} entry point '{entry_name}' input",
                )
            else:
                note_other(
                    parameter.param_type,
                    f"the {stage_name} entry point '{entry_name}' output",
                )
    return vertex_inputs, other_uses


def _direction(node, default="input"):
    names = {
        str(qualifier).lower() for qualifier in getattr(node, "qualifiers", None) or []
    }
    names.update(
        str(getattr(attribute, "name", "")).lower()
        for attribute in getattr(node, "attributes", None) or []
    )
    if "inout" in names or "out" in names or "output" in names:
        return "output"
    if "in" in names or "input" in names:
        return "input"
    return default


def _is_inout(node):
    return any(
        str(qualifier).lower() == "inout"
        for qualifier in getattr(node, "qualifiers", None) or []
    )


def _type_name(type_node):
    name = getattr(type_node, "name", None)
    return name if isinstance(name, str) else str(type_node or "")


def _stage_name(stage):
    value = getattr(stage, "stage", None)
    return str(getattr(value, "value", value) or "").lower()


def _stages(program):
    stages = getattr(program, "stages", None) or {}
    return list(stages.values()) if isinstance(stages, dict) else list(stages)
