CONTRACTION_PROBE_HLSL = """
    cbuffer _ : register(b0) { float scale; float bias; int count; }
    Texture2D<float4> source : register(t0);
    SamplerState linearSampler : register(s0);
    RWStructuredBuffer<float4> results : register(u0);
    RWTexture2D<float4> image : register(u1);
    groupshared float shared[64];
    static float accumulator;

    float Weighted(float x, float y) { x = x * scale + y; return x; }
    void Accumulate(inout float total, float value) { total += value * scale + bias; }
    float2 Select(float2 a, float2 b) { return (b - a).yx * float2(-1, 1); }

    [NumThreads(64, 1, 1)]
    void Execute(uint3 ThreadIds : SV_DispatchThreadID, uint GroupIndex : SV_GroupIndex)
    {
        float4 p = results[ThreadIds.x];
        shared[GroupIndex] = p.x * p.y + p.z;
        GroupMemoryBarrierWithGroupSync();
        float total = 0;
        for (int i = 0; i < count && p.x * scale + bias < 4.0; i++)
        {
            Accumulate(total, shared[i] * p.w + bias);
        }
        if (p.y * scale + bias > 0.5) total += 1;
        float t = (p.z * p.w + bias > 0.25) ? p.x : p.y;
        accumulator = p.x * p.w + t;
        results[ThreadIds.x] = float4(
            Select(p.xy, p.zw), Weighted(p.x, p.y) * bias + total, accumulator);
        results[ThreadIds.x].w += p.x * p.y;
        image[ThreadIds.xy] = source.SampleLevel(
            linearSampler, p.xy * scale + bias, 0).zyxw * p.w + bias;
        results[0].x = (p * scale + bias)[1] + max(p.xy, p.zw * scale + bias).y;
    }
"""

FLOAT_SPIRV_OPERATIONS = (
    "OpFAdd",
    "OpFSub",
    "OpFMul",
    "OpVectorTimesScalar",
    "OpMatrixTimesScalar",
    "OpVectorTimesMatrix",
    "OpMatrixTimesVector",
    "OpMatrixTimesMatrix",
    "OpDot",
)
MESA_ENV = "CROSSTL_REQUIRE_MESA_NIR_EXACTNESS"
NIR_INSTRUCTION = re.compile(r"^\s*\d+(?:x\d+)?\s+%\d+ = (\w+)(!?) ")


def test_opengl_evaluates_precise_functions_as_written(tmp_path):
    code = translate(CONTRACTION_PROBE_HLSL, tmp_path, "opengl")

    # Float locals are precise; an integer local that no float arithmetic
    # reaches is not. A written value parameter is copied into a precise local
    # and an output parameter is qualified.
    assert "precise vec4 p = results[gl_GlobalInvocationID.x];" in code
    assert "for (int i = 0; " in code
    assert re.search(
        r"float Weighted\(float (\w+), float y\) \{\n    precise float x = \1;", code
    )
    assert "void Accumulate(precise inout float total, float value) {" in code
    # Conditions, user-function arguments and values stored outside the
    # function's locals go through precise locals declared at entry.
    for pattern in (
        r"for \(int i = 0; \((\w+) = \(\(i < count\) && ",
        r"if \(\((\w+) = \(\(\(p\.y \* scale\) \+ bias\) > 0\.5\)\)\)",
        r"precise float t = \(\((\w+) = \(\(\(p\.z \* p\.w\) \+ bias\) > 0\.25\)\)",
        r"Accumulate\(total, \((\w+) = \(\(shared_\[i\] \* p\.w\) \+ bias\)\)\)",
        r"shared_\[gl_LocalInvocationIndex\] = \((\w+) = \(\(p\.x \* p\.y\) \+ p\.z\)\)",
        r"accumulator = \((\w+) = \(\(p\.x \* p\.w\) \+ t\)\)",
        r"results\[gl_GlobalInvocationID\.x\]\.w = \((\w+) = "
        r"\(results\[gl_GlobalInvocationID\.x\]\.w \+ \(p\.x \* p\.y\)\)\)",
        # Selections from computed values capture the value first.
        r"\((\w+) = \(b - a\)\)\.yx",
        r"\((\w+) = textureLod\(source, \(\(p\.xy \* scale\) \+ bias\), 0\)\)\.zyxw",
        r"\((\w+) = \(\(p \* scale\) \+ bias\)\)\[1\]",
        r"\((\w+) = max\(p\.xy, \(\(p\.zw \* scale\) \+ bias\)\)\)\.y",
    ):
        match = re.search(pattern, code)
        assert match is not None, pattern
        assert re.search(rf"\n    precise \w+ {match.group(1)};\n", code), pattern
    validate_glsl_if_available(code, tmp_path)


def test_glslang_marks_every_float_operation_no_contraction(tmp_path):
    validator = shutil.which("glslangValidator")
    disassembler = shutil.which("spirv-dis")
    if validator is None or disassembler is None:
        pytest.skip("glslangValidator and spirv-dis are required")
    code = translate(CONTRACTION_PROBE_HLSL, tmp_path, "opengl")
    source = tmp_path / "probe.comp"
    source.write_text(code, encoding="utf-8")
    module = tmp_path / "probe.spv"
    compiled = subprocess.run(
        [validator, "-G", "--target-env", "opengl", "-o", str(module), str(source)],
        capture_output=True,
        text=True,
    )
    assert compiled.returncode == 0, compiled.stdout + compiled.stderr
    disassembly = subprocess.run(
        [disassembler, "--raw-id", str(module)], capture_output=True, text=True
    ).stdout
    exact = set(re.findall(r"OpDecorate (%\d+) NoContraction", disassembly))
    operations = re.findall(
        rf"(%\d+) = ({'|'.join(FLOAT_SPIRV_OPERATIONS)})\b", disassembly
    )
    assert len(operations) >= 30, operations
    contractible = [op for result, op in operations if result not in exact]
    assert contractible == [], contractible


def test_mesa_keeps_every_float_operation_exact(tmp_path):
    """Mesa marks the NIR it compiles from precise expressions exact."""
    if os.environ.get(MESA_ENV) != "1":
        pytest.skip(f"set {MESA_ENV}=1 to compile on Mesa and inspect its NIR")
    code = translate(CONTRACTION_PROBE_HLSL, tmp_path, "opengl")
    source = tmp_path / "probe.comp"
    source.write_text(code, encoding="utf-8")
    compile_on_driver = textwrap.dedent("""
        import sys
        import moderngl
        context = moderngl.create_standalone_context(backend="egl", require=430)
        print("renderer:", context.info["GL_RENDERER"], flush=True)
        context.compute_shader(open(sys.argv[1], encoding="utf-8").read())
        """)
    completed = subprocess.run(
        [sys.executable, "-c", compile_on_driver, str(source)],
        capture_output=True,
        text=True,
        timeout=120,
        env=dict(os.environ, MESA_GLSL="dump", MESA_SHADER_CACHE_DISABLE="true"),
    )
    output = completed.stdout + completed.stderr
    assert completed.returncode == 0, output[-4000:]
    operations = [
        (match.group(1), bool(match.group(2)))
        for match in map(NIR_INSTRUCTION.match, output.splitlines())
        if match is not None and match.group(1) in {"fadd", "fmul", "ffma"}
    ]
    assert len(operations) >= 30, output[-4000:]
    inexact = [operation for operation, exact in operations if not exact]
    assert inexact == [], (len(inexact), len(operations))


PRECISE_FUNCTION_HLSL = """
    RWStructuredBuffer<float> results : register(u0);
    precise float Stable(float a, float b, float c) { return a * b + c; }
    float Relaxed(float a, float b, float c) { return a * b + c; }
    [NumThreads(1, 1, 1)]
    void Execute(uint3 ThreadIds : SV_DispatchThreadID)
    {
        results[0] = Stable(results[1], results[2], results[3])
            + Relaxed(results[1], results[2], results[3]);
    }
"""


def test_precise_functions_stay_precise_on_every_target(tmp_path):
    options = {"matrix_packing": "row_major"}
    metal = translate(PRECISE_FUNCTION_HLSL, tmp_path, "metal", options)
    assert (
        "float Stable(float a, float b, float c) {\n"
        "    #pragma clang fp contract(off)\n"
    ) in metal
    assert metal.count("#pragma clang fp contract(off)") == 1

    glsl = translate(PRECISE_FUNCTION_HLSL, tmp_path, "opengl", options)
    assert "float Stable(float a, float b, float c);" in glsl
    assert "precise float crossglPreciseReturn = ((a * b) + c);" in glsl
    assert glsl.count("precise float") == 1
    validate_glsl_if_available(glsl, tmp_path)

    hlsl = translate(PRECISE_FUNCTION_HLSL, tmp_path, "directx", options)
    assert "precise float Stable(float a, float b, float c)" in hlsl
    assert "precise float Relaxed" not in hlsl

    slang = translate(PRECISE_FUNCTION_HLSL, tmp_path, "slang", options)
    assert "precise float Stable(float a, float b, float c)\n" in slang
    assert ": precise" not in slang

    if metal_compiler() is not None:
        path = tmp_path / "precise.metal"
        path.write_text(metal, encoding="utf-8")
        completed = subprocess.run(
            ["xcrun", "-sdk", "macosx", "metal", "-c", str(path), "-o", "/dev/null"],
            capture_output=True,
            text=True,
        )
        assert completed.returncode == 0, completed.stderr
