"""Contraction-free HLSL arithmetic in CrossGL, Metal and OpenGL.

With ``floating_point_contraction="off"`` the HLSL frontend evaluates the
intrinsics DXC lowers to multiplications and additions in DXC's order, with
every product and sum rounded, as WARP executes the DXIL. The sources are
reduced from shaders generated by ComputeSharp.
"""

import os
import re
import shutil
import subprocess
import sys
import textwrap

import numpy as np
import pytest

import crosstl
from crosstl.backend.DirectX import DirectxCrossGLCodeGen
from crosstl.backend.DirectX.DirectxLexer import HLSLLexer
from crosstl.backend.DirectX.DirectxParser import HLSLParser
from crosstl.backend.DirectX.precise_arithmetic import HLSLPreciseArithmeticError

ARITHMETIC_HLSL = """
    cbuffer _ : register(b0) { float time; float3x3 rotation; float4x4 world; }
    StructuredBuffer<float3> source : register(t0);
    RWStructuredBuffer<float4> results : register(u0);
    static const float3 Up = normalize(float3(0, 1, 1));
    float3 Shade(float3 n, float3 l, float t)
    {
        float3 h = normalize(n + l);
        float3 r = reflect(-l, n);
        float s = smoothstep(0.1, 0.9, t);
        float3 c = cross(n, l);
        float3 f = faceforward(n, l, h);
        return lerp(h, r * s, 0.25) + c * dot(n, l) + f + length(c)
            + distance(n, l) + mad(t, 2.0, 1.0);
    }
    [NumThreads(64, 1, 1)]
    void Execute(uint3 ThreadIds : SV_DispatchThreadID)
    {
        float3 p = source[ThreadIds.x];
        float2x3 wide = float2x3(p, p.zyx);
        float3 q = mul(p, rotation);
        float3 w = mul(rotation, p);
        float2 v2 = mul(wide, p);
        float3 v3 = mul(p.xy, wide);
        float3x3 m = mul(rotation, rotation);
        float4 h4 = mul(float4(p, 1), world);
        float2 edge = normalize((p - q).yx * float2(-1, 1));
        float scalar = lerp(p.x, p.y, 0.5) + dot(p.x, p.y) + length(p.z)
            + smoothstep(0, 1, mul(m, p).x) + edge.x;
        results[ThreadIds.x] = float4(
            Shade(q + w + m[0] + v3, Up, time) + h4.xyz, scalar + v2.x);
    }
"""

OFF = {
    "matrix_packing": "row_major",
    "floating_point_contraction": "off",
}


def translate(code, tmp_path, backend, options=OFF):
    path = tmp_path / "arithmetic.hlsl"
    path.write_text(textwrap.dedent(code).strip() + "\n", encoding="utf-8")
    return crosstl.translate(
        str(path), backend=backend, format_output=False, source_options=options
    )


def generate_crossgl(code, **options):
    ast = HLSLParser(HLSLLexer(textwrap.dedent(code).strip()).tokenize()).parse()
    return DirectxCrossGLCodeGen.HLSLToCrossGLConverter(**options).generate(ast)


def validate_glsl_if_available(source, tmp_path):
    validator = shutil.which("glslangValidator")
    if validator is None:
        return
    path = tmp_path / "shader.comp"
    path.write_text(source, encoding="utf-8")
    completed = subprocess.run(
        [validator, "-S", "comp", str(path)], capture_output=True, text=True
    )
    assert completed.returncode == 0, completed.stdout + completed.stderr


def metal_compiler():
    xcrun = shutil.which("xcrun")
    if xcrun is None:
        return None
    probe = subprocess.run(
        [xcrun, "-sdk", "macosx", "-f", "metal"], capture_output=True, text=True
    )
    return xcrun if probe.returncode == 0 else None


def test_intrinsics_expand_in_dxc_order(tmp_path):
    code = translate(ARITHMETIC_HLSL, tmp_path, "opengl")

    assert (
        "precise float crossglPreciseReturn = "
        "(((a.x * b.x) + (a.y * b.y)) + (a.z * b.z));"
    ) in code
    assert "precise vec3 crossglPreciseReturn = (a + (t * (b - a)));" in code
    assert "precise float t = clamp(((x - low) / (high - low)), 0.0, 1.0);" in code
    assert "((t * t) * (3.0 - (2.0 * t)))" in code
    assert "(v * inversesqrt(crosstl_hlsl_dot_vec3(v, v)))" in code
    assert "(v * inversesqrt(crosstl_hlsl_dot_vec2(v, v)))" in code
    assert "sqrt(crosstl_hlsl_dot_vec3(v, v))" in code
    assert "precise vec3 difference = (a - b);" in code
    assert "(i - (n * (2.0 * crosstl_hlsl_dot_vec3(i, n))))" in code
    assert "((crosstl_hlsl_dot_vec3(i, ng) < 0.0) ? n : (-n))" in code
    assert (
        "vec3(((a.y * b.z) - (a.z * b.y)), ((a.z * b.x) - (a.x * b.z)), "
        "((a.x * b.y) - (a.y * b.x)))"
    ) in code
    # mad and scalar forms need no helper.
    assert "((t * 2.0) + 1.0)" in code
    assert "crosstl_hlsl_lerp_float(p.x, p.y, 0.5)" in code
    assert "(p.x * p.y)" in code
    assert "abs(p.z)" in code
    assert "crosstl_hlsl_smoothstep_float(float(0), float(1), " in code
    assert re.search(
        r"crosstl_hlsl_lerp_vec3\(h, \(crossglPreciseArgument\w* = \(r \* s\)\), "
        r"vec3\(0\.25\)\)",
        code,
    )
    # Every remaining builtin call is one DXC folds at compile time.
    assert "const vec3 Up = normalize(vec3(0, 1, 1));" in code
    for builtin in ("dot", "mix", "length", "distance", "cross", "reflect"):
        assert re.search(rf"(?<![\w.]){builtin}\(", code) is None, builtin
    assert len(re.findall(r"(?<![\w.])normalize\(", code)) == 1
    validate_glsl_if_available(code, tmp_path)


def test_matrix_products_accumulate_from_the_first_term(tmp_path):
    code = translate(ARITHMETIC_HLSL, tmp_path, "opengl")

    # Row-major packing holds HLSL rows as CrossGL columns: mul(p, rotation)
    # is the CrossGL product rotation * p.
    assert "vec3 q = crosstl_hlsl_mul_mat3_vec3(rotation, p);" in code
    assert "vec3 w = crosstl_hlsl_mul_vec3_mat3(p, rotation);" in code
    assert "vec2 v2 = crosstl_hlsl_mul_vec3_mat2x3(p, wide);" in code
    assert "vec3 v3 = crosstl_hlsl_mul_mat2x3_vec2(wide, p.xy);" in code
    assert "mat3 m = crosstl_hlsl_mul_mat3_mat3(rotation, rotation);" in code
    assert "crosstl_hlsl_mul_mat4_vec4(world, vec4(p, 1))" in code
    assert (
        "vec3((((left[0][0] * right.x) + (left[1][0] * right.y)) + "
        "(left[2][0] * right.z)), "
    ) in code
    # CrossGL mat2x3 has two columns and three rows, like GLSL mat2x3.
    assert "vec3 crosstl_hlsl_mul_mat2x3_vec2(mat2x3 left, vec2 right) {" in code
    assert "vec2 crosstl_hlsl_mul_vec3_mat2x3(vec3 left, mat2x3 right) {" in code
    validate_glsl_if_available(code, tmp_path)


class Vector(list):
    x = property(lambda self: self[0])
    y = property(lambda self: self[1])
    z = property(lambda self: self[2])
    w = property(lambda self: self[3])


def evaluate_helper(crossgl, name, left, right):
    """Evaluate a generated CrossGL product helper with Python numbers."""
    match = re.search(rf" crosstl_hlsl_{name}\([^)]*\) {{\n\s*return (.*?);\n", crossgl)
    assert match is not None, name
    constructors = {
        f"{kind}{size}": lambda *items: Vector(items)
        for kind in ("vec", "mat")
        for size in ("2", "3", "4", "2x3", "3x2")
    }
    return eval(match.group(1), constructors, {"left": left, "right": right})


def crossgl_value(hlsl_value):
    """Row-major packing: a CrossGL column holds an HLSL row."""
    array = np.asarray(hlsl_value, dtype=float)
    if array.ndim == 1:
        return Vector(array.tolist())
    return [Vector(row.tolist()) for row in array]


def test_matrix_product_helpers_reproduce_hlsl_mul(tmp_path):
    crossgl = translate(ARITHMETIC_HLSL, tmp_path, "cgl")
    rng = np.random.default_rng(7)
    rotation = rng.normal(size=(3, 3))
    wide = rng.normal(size=(2, 3))
    p = rng.normal(size=3)

    cases = [
        ("mul_mat3_vec3", rotation, p, p @ rotation),
        ("mul_vec3_mat3", p, rotation, rotation @ p),
        ("mul_vec3_mat2x3", p, wide, wide @ p),
        ("mul_mat2x3_vec2", wide, p[:2], p[:2] @ wide),
    ]
    for name, cgl_left, cgl_right, expected in cases:
        actual = evaluate_helper(
            crossgl, name, crossgl_value(cgl_left), crossgl_value(cgl_right)
        )
        np.testing.assert_allclose(np.asarray(actual), expected, rtol=1e-12)
    product = evaluate_helper(
        crossgl,
        "mul_mat3_mat3",
        crossgl_value(rotation),
        crossgl_value(rotation),
    )
    np.testing.assert_allclose(np.asarray(product), rotation @ rotation, rtol=1e-12)


def test_every_function_is_precise(tmp_path):
    crossgl = translate(ARITHMETIC_HLSL, tmp_path, "cgl")
    assert "    @ precise\n    vec3 Shade(vec3 n, vec3 l, float t) {" in crossgl
    assert "    @ NumThreads(64, 1, 1)\n    @ precise\n    void Execute(" in crossgl

    metal = translate(ARITHMETIC_HLSL, tmp_path, "metal")
    for signature in ("float3 Shade(", "kernel void Execute("):
        body = metal.index("{\n", metal.index(signature))
        assert metal.startswith("{\n    #pragma clang fp contract(off)\n", body)


def test_metal_keeps_every_product_and_sum_separate(tmp_path):
    metal = translate(ARITHMETIC_HLSL, tmp_path, "metal")
    xcrun = metal_compiler()
    if xcrun is None:
        pytest.skip("the Metal toolchain is not available")
    source = tmp_path / "arithmetic.metal"
    source.write_text(metal, encoding="utf-8")
    ir = tmp_path / "arithmetic.ll"
    completed = subprocess.run(
        [xcrun, "-sdk", "macosx", "metal", "-S", "-emit-llvm", "-O2"]
        + [str(source), "-o", str(ir)],
        capture_output=True,
        text=True,
    )
    assert completed.returncode == 0, completed.stderr
    kernel = re.search(r"define [^\n]*@Execute\(.*?\n}\n", ir.read_text(), re.S)
    assert kernel is not None
    body = kernel.group(0)
    # Metal's dot, mix, smoothstep, cross, reflect and matrix products fuse.
    for fused in ("llvm.fmuladd", "llvm.fma", "air.mix", "air.fma"):
        assert fused not in body, fused
    assert " contract " not in body
    # Only the constant DXC folds at compile time keeps the dot intrinsic.
    dots = re.findall(r"@air\.dot\.v\d+f32\(([^)]*)\)", body)
    assert dots
    for operands in dots:
        assert "%" not in operands, operands


def test_integer_and_constant_operands_keep_the_intrinsic():
    crossgl = generate_crossgl(
        """
        static const float Width = length(float2(3, 4));
        RWStructuredBuffer<int> results : register(u0);
        [NumThreads(1, 1, 1)]
        void Execute(uint3 ThreadIds : SV_DispatchThreadID)
        {
            int3 a = int3(ThreadIds);
            int2x2 m = int2x2(1, 2, 3, 4);
            int2 v = mul(m, a.xy);
            results[0] = dot(a, int3(1, 2, 3)) + v.x + (int)Width
                + (int)dot(float2(1, 2), float2(3, 4));
        }
        """,
        matrix_packing="row_major",
        floating_point_contraction="off",
    )
    assert "const float Width = length(vec2(3, 4));" in crossgl
    assert "dot(a, ivec3(1, 2, 3))" in crossgl
    assert "dot(vec2(1, 2), vec2(3, 4))" in crossgl
    assert "crosstl_hlsl_mul" not in crossgl
    assert "crosstl_hlsl_dot" not in crossgl


def test_operand_types_follow_overloads_and_float_intrinsics():
    # Reduced from TerracedHills and ExtrudedTruchetPattern.
    crossgl = generate_crossgl(
        """
        static float Tri(in float x);
        static float2 Tri(in float2 x);
        static float Tri(in float x) { return abs(frac(x) - 0.5); }
        static float2 Tri(in float2 x) { return abs(frac(x) - 0.5); }
        RWStructuredBuffer<float> results : register(u0);
        [NumThreads(1, 1, 1)]
        void Execute(uint3 ThreadIds : SV_DispatchThreadID)
        {
            float2 p = float2(ThreadIds.xy);
            results[0] = dot(Tri(p / 1.5 + Tri(p.yx / 3.0 + 0.25)), 1)
                + dot(pow(p, 3), 1) + Tri(p.x);
        }
        """,
        matrix_packing="row_major",
        floating_point_contraction="off",
    )
    assert "crosstl_hlsl_dot_vec2(Tri(" in crossgl
    assert "crosstl_hlsl_dot_vec2(pow(p, 3), vec2(1))" in crossgl
    assert "dot(" not in crossgl.replace("crosstl_hlsl_dot_vec2(", "")


