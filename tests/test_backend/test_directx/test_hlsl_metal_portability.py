"""HLSL semantics that must survive translation to CrossGL and Metal.

The sources are reduced from shaders generated by ComputeSharp, whose HLSL
relies on texture element types, implicit conversions, row-major matrix
packing and thread-private globals.
"""

import shutil
import subprocess
import textwrap

import pytest

from crosstl.backend.DirectX import DirectxCrossGLCodeGen
from crosstl.backend.DirectX.DirectxLexer import HLSLLexer
from crosstl.backend.DirectX.DirectxParser import HLSLParser
from crosstl.translator.codegen.metal_codegen import MetalCodeGen
from crosstl.translator.lexer import Lexer as CrossGLLexer
from crosstl.translator.parser import Parser as CrossGLParser
from tests.metal_refusal_helpers import metal_partial_output, refused_metal


def generate_crossgl(code: str, **options) -> str:
    ast = HLSLParser(HLSLLexer(textwrap.dedent(code).strip()).tokenize()).parse()
    return DirectxCrossGLCodeGen.HLSLToCrossGLConverter(**options).generate(ast)


def generate_metal(code: str, **options) -> str:
    crossgl = generate_crossgl(code, **options)
    ast = CrossGLParser(CrossGLLexer(crossgl).get_tokens()).parse()
    return MetalCodeGen().generate(ast)


def compile_metal_if_available(source: str, tmp_path) -> None:
    xcrun = shutil.which("xcrun")
    if xcrun is None:
        return
    probe = subprocess.run(
        [xcrun, "-sdk", "macosx", "-f", "metal"], capture_output=True, text=True
    )
    if probe.returncode != 0:
        return
    path = tmp_path / "shader.metal"
    path.write_text(source)
    completed = subprocess.run(
        [xcrun, "-sdk", "macosx", "metal", "-c", str(path), "-o", str(tmp_path / "a")],
        capture_output=True,
        text=True,
    )
    assert completed.returncode == 0, completed.stderr


TEXEL_HLSL = """
    Texture2D<float> depth : register(t0);
    Texture2D<int2> offsets : register(t1);
    Texture3D<uint> labels : register(t2);
    RWTexture2D<float> coverage : register(u0);
    RWTexture2D<float2> motion : register(u1);
    RWTexture3D<int4> ids : register(u2);
    RWStructuredBuffer<float> results : register(u3);

    [NumThreads(8, 8, 1)]
    void Execute(uint3 ThreadIds : SV_DispatchThreadID)
    {
        float d = depth[ThreadIds.xy];
        int2 o = offsets[ThreadIds.xy];
        uint label = labels[ThreadIds];
        coverage[ThreadIds.xy] = d + coverage[ThreadIds.xy];
        coverage[ThreadIds.xy] += 2.0 * d;
        motion[ThreadIds.xy] = float2(d, (float)o.y);
        results[ThreadIds.x] = motion[ThreadIds.xy].y + depth.Load(int3(ThreadIds.xy, 0)) + label;
        ids[ThreadIds].xyz = ThreadIds;
        ids[ThreadIds].w = 7;
    }
"""


def test_texture_reads_return_the_declared_element_type():
    crossgl = generate_crossgl(TEXEL_HLSL)

    assert "itexture2D offsets;" in crossgl
    assert "utexture3D labels;" in crossgl
    assert "float d = texelFetch(depth, ThreadIds.xy, 0).x;" in crossgl
    assert "ivec2 o = texelFetch(offsets, ThreadIds.xy, 0).xy;" in crossgl
    assert "uint label = texelFetch(labels, ThreadIds, 0).x;" in crossgl
    # A swizzle within the element reads the texel once, without re-narrowing.
    assert "imageLoad(motion, ThreadIds.xy).y" in crossgl
    assert "imageLoad(motion, ThreadIds.xy).xy.y" not in crossgl
    # Load folds the mip level out of the coordinate and narrows like indexing.
    assert (
        "(imageLoad(motion, ThreadIds.xy).y + texelFetch(depth, ThreadIds.xy, 0).x)"
        in crossgl
    )


def test_storage_image_stores_widen_values_to_four_components():
    crossgl = generate_crossgl(TEXEL_HLSL)

    assert (
        "imageStore(coverage, ThreadIds.xy, "
        "vec4(texelFetch(depth, ThreadIds.xy, 0).x + imageLoad(coverage, "
        "ThreadIds.xy).x, 0.0, 0.0, 1.0));"
    ) not in crossgl
    assert (
        "imageStore(coverage, ThreadIds.xy, vec4(d + imageLoad(coverage, "
        "ThreadIds.xy).x, 0.0, 0.0, 1.0));"
    ) in crossgl
    # Compound stores keep the right operand grouped.
    assert (
        "imageStore(coverage, ThreadIds.xy, vec4(imageLoad(coverage, "
        "ThreadIds.xy).x + (2.0 * d), 0.0, 0.0, 1.0));"
    ) in crossgl
    assert (
        "imageStore(motion, ThreadIds.xy, vec4(vec2(d, float(o.y)), 0.0, 1.0));"
        in crossgl
    )


def test_partial_storage_image_component_stores_read_modify_write():
    crossgl = generate_crossgl(TEXEL_HLSL)

    assert "ivec4 _texel1 = imageLoad(ids, ThreadIds);" in crossgl
    assert "_texel1.xyz = ThreadIds;" in crossgl
    assert "imageStore(ids, ThreadIds, _texel1);" in crossgl
    assert "_texel2.w = 7;" in crossgl


def test_partial_storage_image_store_rejects_side_effecting_coordinates():
    with pytest.raises(ValueError, match="side-effect-free texel coordinate"):
        generate_crossgl("""
            RWTexture2D<float4> image : register(u0);
            RWStructuredBuffer<uint> counter : register(u1);

            [NumThreads(1, 1, 1)]
            void Execute(uint3 ThreadIds : SV_DispatchThreadID)
            {
                uint slot;
                InterlockedAdd(counter[0], 1, slot);
                image[uint2(counter.IncrementCounter(), 0)].x = 1.0;
            }
        """)


def test_metal_texel_reads_writes_and_fences(tmp_path):
    metal = generate_metal(TEXEL_HLSL)

    assert "texture2d<int> offsets [[texture(1)]]" in metal
    assert "texture3d<uint> labels [[texture(2)]]" in metal
    assert "float d = depth.read(uint2(ThreadIds.xy), uint(0)).x;" in metal
    assert "int4 _texel1 = ids.read(uint3(ThreadIds));" in metal
    assert "_texel1.xyz = int3(ThreadIds);" in metal
    lines = [line.strip() for line in metal.splitlines()]
    # A read_write texture read after the same thread's write needs a fence.
    first_store = lines.index("ids.write(_texel1, uint3(ThreadIds));")
    assert lines[first_store + 1] == "ids.fence();"
    assert "int4 _texel2 = ids.read(uint3(ThreadIds));" in lines[first_store + 2 :]
    # Images that are only written are not fenced.
    assert "motion.fence();" in metal
    compile_metal_if_available(metal, tmp_path)


ROW_MAJOR_HLSL = """
    cbuffer _ : register(b0)
    {
        float4x4 world;
    }
    RWStructuredBuffer<float> results : register(u0);

    static float2x2 Rotate(float a)
    {
        float c = cos(a);
        float s = sin(a);
        return float2x2(c, s, -s, c);
    }

    [NumThreads(1, 1, 1)]
    void Execute(uint3 ThreadIds : SV_DispatchThreadID)
    {
        float2 v = float2(1.0, 2.0);
        float2 rotated = mul(v, Rotate(0.5));
        float2 applied = mul(Rotate(0.5) * 2.0, v + 1.0);
        float4 p = mul(float4(v, 0.0, 1.0), world);
        float d = mul(v, rotated);
        float2x2 r = Rotate(0.25);
        results[0] = rotated.x + applied.y + p.x + d + r._m01 + r._21 + r._m00_m11.y;
    }
"""


def test_row_major_packing_orders_matrix_products():
    crossgl = generate_crossgl(ROW_MAJOR_HLSL, matrix_packing="row_major")

    assert "vec2 rotated = (Rotate(0.5) * v);" in crossgl
    assert "vec2 applied = ((v + 1.0) * (Rotate(0.5) * 2.0));" in crossgl
    assert "vec4 p = (world * vec4(v, 0.0, 1.0));" in crossgl
    assert "float d = dot(v, rotated);" in crossgl
    assert "r[0][1]" in crossgl
    assert "r[1][0]" in crossgl
    assert "vec2(r[0][0], r[1][1]).y" in crossgl


def test_default_packing_keeps_matrix_product_order_and_dots_vectors():
    crossgl = generate_crossgl(ROW_MAJOR_HLSL)

    assert "vec2 rotated = (v * Rotate(0.5));" in crossgl
    assert "float d = dot(v, rotated);" in crossgl


def test_row_major_packing_rejects_unknown_mul_operands():
    with pytest.raises(ValueError, match="Cannot order HLSL mul operands"):
        generate_crossgl(
            """
            RWStructuredBuffer<float4> results : register(u0);

            [NumThreads(1, 1, 1)]
            void Execute(uint3 ThreadIds : SV_DispatchThreadID)
            {
                results[0] = mul(results[1], undeclared);
            }
            """,
            matrix_packing="row_major",
        )


def test_matrix_packing_option_is_validated():
    with pytest.raises(ValueError, match="matrix_packing"):
        DirectxCrossGLCodeGen.HLSLToCrossGLConverter(matrix_packing="rows")


def test_metal_row_major_matrix_products_compile(tmp_path):
    metal = generate_metal(ROW_MAJOR_HLSL, matrix_packing="row_major")

    assert "float2 rotated = Rotate(0.5) * v;" in metal
    # A matrix-scalar product stays a matrix rather than a converted vector,
    # and is evaluated before the vector-matrix product as in the source.
    assert "float2 applied = (v + 1.0) * (Rotate(0.5) * 2.0);" in metal
    compile_metal_if_available(metal, tmp_path)


CONVERSION_HLSL = """
    cbuffer _ : register(b0)
    {
        uint __x;
    }
    RWStructuredBuffer<int3> cells : register(u0);
    RWStructuredBuffer<float> values : register(u1);
    StructuredBuffer<float> kernel : register(t0);

    static int total;
    static int scale = 3;

    static float4 Shade(float2 coord)
    {
        return float4(coord, 0.0, 1.0);
    }

    static int __get_Dimension0(RWStructuredBuffer<float> resource)
    {
        uint _0, _1;
        resource.GetDimensions(_0, _1);
        return _0;
    }

    static int __get_Dimension0(StructuredBuffer<float> resource)
    {
        uint _0, _1;
        resource.GetDimensions(_0, _1);
        return _0;
    }

    [NumThreads(64, 1, 1)]
    void Execute(uint3 ThreadIds : SV_DispatchThreadID)
    {
        int3 cell = ThreadIds;
        cell.xy = ThreadIds.yz;
        cells[ThreadIds.x] = ThreadIds;
        float3 f3 = cell;
        int2 a = int2(1, 2);
        uint2 b = uint2(3, 4);
        int2 c = a & b;
        int2 shifted = a << b;
        float4 x = float4(1.0, 2.0, 3.0, 4.0);
        bool4 greater = x > int4(1, 2, 3, 4);
        float4 m = x % int4(2, 2, 2, 2);
        float r = values[0] % 2.0;
        int kernelLength = __get_Dimension0(kernel);
        total += kernelLength * scale;
        values[ThreadIds.x] = Shade(ThreadIds.xy).y + f3[0] + c.x + shifted.y
            + (greater.x ? 1.0 : 0.0) + m.x + r + total;
        uint original;
        InterlockedCompareExchange(values[0], 1.0, 2.0, original);
    }
"""


def test_metal_makes_source_implicit_conversions_explicit(tmp_path):
    metal = generate_metal(
        CONVERSION_HLSL.replace(
            "InterlockedCompareExchange(values[0], 1.0, 2.0, original);", ""
        )
    )

    assert "int3 cell = int3(ThreadIds);" in metal
    assert "cell.xy = int2(ThreadIds.yz);" in metal
    assert "cells[ThreadIds.x] = int3(ThreadIds);" in metal
    assert "float3 f3 = float3(cell);" in metal
    assert "int2 c = int2(uint2(a) & b);" in metal
    assert "int2 shifted = a << int2(b);" in metal
    assert "bool4 greater = x > float4(int4(1, 2, 3, 4));" in metal
    assert "float4 m = fmod(x, float4(int4(2, 2, 2, 2)));" in metal
    assert "float r = fmod(values[0], 2.0);" in metal
    assert "Shade(float2(ThreadIds.xy))" in metal
    # Indexing a vector yields its component type rather than the vector.
    assert "f3[0] +" in metal
    compile_metal_if_available(metal, tmp_path)


