"""HLSL semantics that must survive translation to CrossGL and OpenGL GLSL.

The sources are reduced from shaders generated by ComputeSharp. They cover
HLSL register classes that share one OpenGL binding table, storage textures
whose format the runtime chooses, unsigned resource coordinates, implicit
operand conversions of builtins and static globals.
"""

import shutil
import subprocess
import textwrap

import pytest

import crosstl
from crosstl.backend.DirectX import DirectxCrossGLCodeGen
from crosstl.backend.DirectX.DirectxLexer import HLSLLexer
from crosstl.backend.DirectX.DirectxParser import HLSLParser


def translate_hlsl(code: str, tmp_path, name: str = "shader.hlsl"):
    path = tmp_path / name
    path.write_text(textwrap.dedent(code).strip() + "\n", encoding="utf-8")
    return crosstl.translate_with_metadata(
        str(path),
        backend="opengl",
        format_output=False,
        source_options={"matrix_packing": "row_major"},
    )


def generate_crossgl(code: str) -> str:
    ast = HLSLParser(HLSLLexer(textwrap.dedent(code).strip()).tokenize()).parse()
    return DirectxCrossGLCodeGen.HLSLToCrossGLConverter().generate(ast)


def validate_glsl_if_available(source: str, tmp_path) -> None:
    validator = shutil.which("glslangValidator")
    if validator is None:
        return
    path = tmp_path / "shader.comp"
    path.write_text(source, encoding="utf-8")
    completed = subprocess.run(
        [validator, "-S", "comp", str(path)], capture_output=True, text=True
    )
    assert completed.returncode == 0, completed.stdout + completed.stderr


def bindings_by_register(result):
    return {
        record["register"]: record
        for record in result.resource_bindings
        if record.get("register") and record["kind"] != "sampler"
    }


REGISTER_HLSL = """
    cbuffer _ : register(b0) { uint __x; uint __y; uint __z; }
    StructuredBuffer<float> source : register(t0);
    RWStructuredBuffer<float> destination : register(u0);
    RWStructuredBuffer<float> extra : register(u1);
    [NumThreads(64, 1, 1)]
    void Execute(uint3 ThreadIds : SV_DispatchThreadID)
    {
        destination[ThreadIds.x] = source[ThreadIds.x] + extra[ThreadIds.x];
    }
"""


def test_register_classes_share_the_storage_buffer_table(tmp_path):
    result = translate_hlsl(REGISTER_HLSL, tmp_path)
    records = bindings_by_register(result)

    assert records["b0"]["namespace"] == "uniform-buffer"
    assert records["b0"]["binding"] == 0
    assert records["t0"]["namespace"] == "shader-storage-buffer"
    assert records["t0"]["binding"] == 0
    # u0 and u1 keep their numbers unless t-registers occupy them.
    assert records["u0"]["binding"] == 1
    assert records["u1"]["binding"] == 2
    assert "binding = 0) readonly buffer sourceBuffer" in result.code
    assert "binding = 1) buffer destinationBuffer" in result.code
    assert "binding = 2) buffer extraBuffer" in result.code
    validate_glsl_if_available(result.code, tmp_path)


def test_register_mapping_does_not_depend_on_declaration_order(tmp_path):
    reordered = REGISTER_HLSL.replace(
        "    StructuredBuffer<float> source : register(t0);\n", ""
    ).replace(
        "RWStructuredBuffer<float> extra : register(u1);",
        "RWStructuredBuffer<float> extra : register(u1);\n"
        "    StructuredBuffer<float> source : register(t0);",
    )
    original = bindings_by_register(translate_hlsl(REGISTER_HLSL, tmp_path, "a.hlsl"))
    moved = bindings_by_register(translate_hlsl(reordered, tmp_path, "b.hlsl"))

    assert {key: value["binding"] for key, value in original.items()} == {
        key: value["binding"] for key, value in moved.items()
    }


def test_overlapping_registers_of_one_class_remain_errors(tmp_path):
    source = """
        RWStructuredBuffer<float> first : register(u0);
        RWStructuredBuffer<float> second : register(u0);
        [NumThreads(1, 1, 1)]
        void Execute(uint3 ThreadIds : SV_DispatchThreadID)
        {
            first[0] = second[0];
        }
    """
    with pytest.raises(ValueError, match="register u"):
        translate_hlsl(source, tmp_path)


SAMPLING_HLSL = """
    cbuffer _ : register(b0) { uint __x; uint __y; uint __z; }
    Texture2D<float4> image : register(t0);
    Texture2D<int2> offsets : register(t1);
    RWTexture2D<unorm float4> output : register(u0);
    RWTexture2D<float2> history : register(u1);
    RWTexture1D<int2> ids : register(u2);
    RWTexture2D<uint> counters : register(u3);
    SamplerState __sampler : register(s);
    [NumThreads(8, 8, 1)]
    void Execute(uint3 ThreadIds : SV_DispatchThreadID)
    {
        output[ThreadIds.xy] = image.SampleLevel(__sampler, float2(0.5, 0.5), 0);
        history[ThreadIds.xy] = history[ThreadIds.xy] + 1;
        ids[ThreadIds.x] = ids[ThreadIds.x] + offsets[ThreadIds.xy];
        InterlockedAdd(counters[ThreadIds.xy], 1u);
    }
"""


def test_samplers_are_reported_for_the_texture_units_they_combine_with(tmp_path):
    result = translate_hlsl(SAMPLING_HLSL, tmp_path)
    samplers = [r for r in result.resource_bindings if r["kind"] == "sampler"]
    texture = bindings_by_register(result)["t0"]

    assert len(samplers) == 1
    assert samplers[0]["name"] == "__sampler"
    assert samplers[0]["namespace"] == "texture"
    assert samplers[0]["binding"] == texture["binding"]
    assert samplers[0]["register"] == "s0"
    assert samplers[0]["texture"] == "image"
    assert "textureLod(image, vec2(0.5, 0.5), 0)" in result.code


def test_storage_textures_take_the_format_of_the_bound_image(tmp_path):
    result = translate_hlsl(SAMPLING_HLSL, tmp_path)
    code = result.code

    assert "@ format(unknown)" in generate_crossgl(SAMPLING_HLSL)
    assert "#extension GL_EXT_shader_image_load_formatted : require" in code
    # Written only: no format and no extension requirement for the image.
    assert "layout(binding = 0) writeonly uniform image2D output_;" in code
    # Read and written: formatless, loaded through the bound image format.
    assert "layout(binding = 1) uniform image2D history;" in code
    assert "layout(binding = 2) uniform iimage1D ids;" in code
    # Atomics require the single-channel 32-bit format.
    assert "layout(r32ui, binding = 3) uniform uimage2D counters;" in code
    # Element types come from the source; loads are not narrowed again.
    assert "imageLoad(ids, int(gl_GlobalInvocationID.x)).xy" in code
    assert ".x.xy" not in code
    validate_glsl_if_available(code, tmp_path)


def test_unsigned_resource_coordinates_are_converted_to_signed(tmp_path):
    code = translate_hlsl(SAMPLING_HLSL, tmp_path).code

    assert "imageStore(output_, ivec2(gl_GlobalInvocationID.xy)" in code
    assert "texelFetch(offsets, ivec2(gl_GlobalInvocationID.xy), 0)" in code
    assert "imageAtomicAdd(counters, ivec2(gl_GlobalInvocationID.xy), 1u)" in code


def test_hlsl_identifiers_reserved_in_glsl_are_escaped(tmp_path):
    source = """
        struct Item
        {
            int Number;
            int Get();
        };
        cbuffer _ : register(b0) { uint __x; uint __y; uint __z; Item item; }
        RWStructuredBuffer<int> output : register(u0);
        static int Twice(RWStructuredBuffer<int> resource);
        int Item::Get()
        {
            return this.Number;
        }
        static int Twice(RWStructuredBuffer<int> resource)
        {
            uint count, stride;
            resource.GetDimensions(count, stride);
            return (int)count * 2;
        }
        int Foo()
        {
            return 2;
        }
        [NumThreads(64, 1, 1)]
        void Execute(uint3 ThreadIds : SV_DispatchThreadID)
        {
            output[ThreadIds.x] = item.Get() + Foo() + Twice(output);
        }
    """
    result = translate_hlsl(source, tmp_path)
    code = result.code

    assert " this" not in code.replace("this_", "")
    assert " resource)" not in code
    # Structured-buffer helpers are only emitted bound to their global buffer.
    assert "int resource_[]" not in code
    assert "Foo()" in code
    validate_glsl_if_available(code, tmp_path)


def test_builtin_operands_follow_hlsl_conversions(tmp_path):
    source = """
        cbuffer _ : register(b0) { uint __x; uint __y; uint __z; }
        RWStructuredBuffer<int> values : register(u0);
        RWStructuredBuffer<float> output : register(u1);
        [NumThreads(64, 1, 1)]
        void Execute(uint3 ThreadIds : SV_DispatchThreadID)
        {
            int2 size = max(1, int2(__x, __y) - 1);
            float3 color = pow(float3(0.5, 0.25, 1), 0.5);
            values[0] = __x * __y * __z;
            values[ThreadIds.x] = ThreadIds.x;
            InterlockedAdd(values[ThreadIds.x], ThreadIds.x);
            int4 v = int4(values[0], values[1], values[2], values[3]);
            bool4 equalToOne = v == 1;
            output[ThreadIds.x] = asfloat(0xFFC00000u) + color.x + size.x
                + (equalToOne.x ? 1 : 0);
        }
    """
    code = translate_hlsl(source, tmp_path).code

    assert "max(ivec2(1), (ivec2(x, y) - 1))" in code
    assert "pow(vec3(0.5, 0.25, 1), vec3(0.5))" in code
    assert "values[0] = int(((x * y) * z));" in code
    assert "values[gl_GlobalInvocationID.x] = int(gl_GlobalInvocationID.x);" in code
    assert (
        "atomicAdd(values[gl_GlobalInvocationID.x], int(gl_GlobalInvocationID.x))"
        in code
    )
    assert "bvec4 equalToOne = equal(v, ivec4(1));" in code
    assert "uintBitsToFloat(4290772992u)" in code
    validate_glsl_if_available(code, tmp_path)


def test_static_globals_are_private_and_zero_initialized(tmp_path):
    source = """
        static int total;
        static float weights[3];
        RWStructuredBuffer<int> output : register(u0);
        [NumThreads(64, 1, 1)]
        void Execute(uint3 ThreadIds : SV_DispatchThreadID)
        {
            for (int i = 0; i < ThreadIds.x; i++)
            {
                total++;
            }
            output[ThreadIds.x] = total + (int)weights[1];
        }
    """
    code = translate_hlsl(source, tmp_path).code

    assert "int total = 0;" in code
    assert "float weights[3] = float[3](0.0, 0.0, 0.0);" in code
    assert "uniform int total" not in code
    validate_glsl_if_available(code, tmp_path)


def test_composite_vector_constructors_keep_vector_arguments(tmp_path):
    source = """
        RWStructuredBuffer<float4> output : register(u0);
        [NumThreads(1, 1, 1)]
        void Execute(uint3 ThreadIds : SV_DispatchThreadID)
        {
            float3 position = float3(1, 2, 3);
            output[0] = float4(sin(float3(5.0, 0.4, 0.2) + position.y * 0.1) * 0.5 + 0.5, 0.08);
        }
    """
    code = translate_hlsl(source, tmp_path).code

    assert (
        "vec4(((sin((vec3(5.0, 0.4, 0.2) + (position.y * 0.1))) * 0.5) + 0.5), 0.08)"
        in code
    )
    validate_glsl_if_available(code, tmp_path)


def test_floating_point_remainder_truncates_like_hlsl(tmp_path):
    source = """
        RWStructuredBuffer<float4> output : register(u0);
        [NumThreads(1, 1, 1)]
        void Execute(uint3 ThreadIds : SV_DispatchThreadID)
        {
            float4 a = float4(-7, 7, -7.5, 2);
            output[0] = a % 2;
            output[1] = a % float4(3, -3, 2, 1);
        }
    """
    code = translate_hlsl(source, tmp_path).code

    assert "vec4 crossgl_remainder(vec4 x, vec4 y) {" in code
    assert "return x - y * trunc(x / y);" in code
    assert "crossgl_remainder(a, vec4(2))" in code
    assert " mod(" not in code
    validate_glsl_if_available(code, tmp_path)


def test_double_bit_casts_and_compare_exchange(tmp_path):
    source = """
        static const double Nan = asdouble(0x00000000, 0xFFF80000);
        RWStructuredBuffer<double> doubles : register(u0);
        RWStructuredBuffer<int> ints : register(u1);
        [NumThreads(64, 1, 1)]
        void Execute(uint3 ThreadIds : SV_DispatchThreadID)
        {
            doubles[0] = Nan;
            doubles[1] = asdouble(0x00000000, 0x7FF00000);
            int original;
            InterlockedCompareExchange(ints[ThreadIds.x], ThreadIds.x, ThreadIds.x * 2, original);
            ints[0] = original;
        }
    """
    code = translate_hlsl(source, tmp_path).code

    assert "const double Nan" not in code
    assert "packDouble2x32(uvec2(0u, 4294443008u))" in code
    assert "packDouble2x32(uvec2(0u, 2146435072u))" in code
    assert "atomicCompSwap(ints[gl_GlobalInvocationID.x], int(" in code
    assert "atomicCompareExchange" not in code
    validate_glsl_if_available(code, tmp_path)


def test_non_square_matrix_constructors_match_their_declarations(tmp_path):
    source = """
        RWStructuredBuffer<float> output : register(u0);
        [NumThreads(1, 1, 1)]
        void Execute(uint3 ThreadIds : SV_DispatchThreadID)
        {
            float2x3 m = float2x3(1, 2, 3, 4, 5, 6);
            float3 v = mul(float2(1, 0), m);
            output[0] = v.z;
        }
    """
