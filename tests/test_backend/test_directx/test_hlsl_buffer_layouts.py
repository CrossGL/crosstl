"""HLSL buffer layouts that must survive translation to CrossGL and Metal.

The host writes constant buffers with the HLSL packing rules and structured
buffers with four-byte alignment. The sources are reduced from shaders
generated by ComputeSharp; the expected offsets are the DXC offsets.
"""

import shutil
import subprocess
import textwrap

import pytest

from crosstl.backend.DirectX import DirectxCrossGLCodeGen
from crosstl.backend.DirectX.DirectxLexer import HLSLLexer
from crosstl.backend.DirectX.DirectxParser import HLSLParser
from crosstl.translator.codegen.metal_codegen import MetalCodeGen
from crosstl.translator.lexer import Lexer as CrossGLLexer
from crosstl.translator.parser import Parser as CrossGLParser


def generate_crossgl(code: str) -> str:
    ast = HLSLParser(HLSLLexer(textwrap.dedent(code).strip()).tokenize()).parse()
    return DirectxCrossGLCodeGen.HLSLToCrossGLConverter(
        matrix_packing="row_major"
    ).generate(ast)


def generate_metal_from_crossgl(crossgl: str) -> str:
    ast = CrossGLParser(CrossGLLexer(crossgl).get_tokens()).parse()
    return MetalCodeGen().generate(ast)


def generate_metal(code: str) -> str:
    return generate_metal_from_crossgl(generate_crossgl(code))


def metal_compiler():
    xcrun = shutil.which("xcrun")
    if xcrun is None:
        return None
    probe = subprocess.run(
        [xcrun, "-sdk", "macosx", "-f", "metal"], capture_output=True, text=True
    )
    if probe.returncode != 0:
        return None
    return xcrun


def compile_metal_with_layout(source, tmp_path, offsets=(), sizes=()):
    """Compile with static assertions on the byte layout when Metal is available."""
    xcrun = metal_compiler()
    if xcrun is None:
        return
    checks = [
        f'static_assert(__builtin_offsetof({struct}, {member}) == {offset}, "{struct}.{member}");'
        for struct, member, offset in offsets
    ]
    checks += [
        f'static_assert(sizeof({struct}) == {size}, "sizeof {struct}");'
        for struct, size in sizes
    ]
    path = tmp_path / "shader.metal"
    path.write_text(source + "\n" + "\n".join(checks) + "\n")
    completed = subprocess.run(
        [xcrun, "-sdk", "macosx", "metal", "-c", str(path), "-o", str(tmp_path / "a")],
        capture_output=True,
        text=True,
    )
    assert completed.returncode == 0, completed.stderr


CONSTANTS_HLSL = """
    struct Cell
    {
        float testX;
        float testY;
        uint seed;
        float distance;
        float spacing;
        float scale;
        int count;
    };

    cbuffer _ : register(b0)
    {
        uint __x;
        uint __y;
        uint __z;
        bool a;
        bool b;
        int c;
        int3 f;
        bool g;
        bool2 h;
        Cell cell;
        float after;
    }

    cbuffer _source : register(b1)
    {
        int source[2];
        bool2 flags[2];
    }

    RWStructuredBuffer<int> results : register(u0);

    [NumThreads(64, 1, 1)]
    void Execute(uint3 ThreadIds : SV_DispatchThreadID)
    {
        if (ThreadIds.x < __x && ThreadIds.y < __y && ThreadIds.z < __z)
        {
            results[0] = int(a) + int(b) + c + f.z + int(g) + int(h.y);
            results[1] = (int)cell.spacing + cell.count + (int)after;
            results[2] = source[ThreadIds.x] + int(all(flags[ThreadIds.x]));
            results[3] = all(h) ? 1 : 0;
        }
    }
"""


def test_reverse_codegen_marks_hlsl_buffer_layouts():
    crossgl = generate_crossgl("""
        cbuffer Params : register(b0) { float scale; }
        RWStructuredBuffer<float> values : register(u0);
        StructuredBuffer<float3> points : register(t0);
        RWByteAddressBuffer raw : register(u1);
        RWTexture2D<float4> image : register(u2);

        [numthreads(1, 1, 1)]
        void main(uint3 id : SV_DispatchThreadID)
        {
            values[id.x] = points[id.x].x * scale + raw.Load(0);
            image[id.xy] = values[id.x];
        }
        """)

    assert "@ buffer_layout(hlsl_cbuffer)\n    cbuffer Params {" in crossgl
    assert (
        "@ buffer_layout(hlsl_structured)\n    RWStructuredBuffer<float> values;"
        in crossgl
    )
    assert (
        "@ buffer_layout(hlsl_structured)\n    StructuredBuffer<float3> points;"
        in crossgl
    )
    assert crossgl.count("@ buffer_layout(") == 3


def test_metal_constant_buffers_reproduce_hlsl_offsets(tmp_path):
    metal = generate_metal(CONSTANTS_HLSL)

    assert "    uint a;\n" in metal
    assert "    packed_int3 f;\n" in metal
    # An eight-byte aligned two-component vector keeps the natural type.
    assert "    uint2 h;\n" in metal
    assert "int(bool(_.a))" in metal
    assert "int(bool2(_.h).y)" in metal
    assert "all(bool2(_.h))" in metal
    assert "    int4 source[2];\n" in metal
    assert "_source.source[ThreadIds.x].x" in metal
    assert "all(bool2(_source.flags[ThreadIds.x].xy))" in metal
    compile_metal_with_layout(
        metal,
        tmp_path,
        offsets=[
            ("_", "a", 12),
            ("_", "b", 16),
            ("_", "c", 20),
            ("_", "f", 32),
            ("_", "g", 44),
            ("_", "h", 48),
            ("_", "cell", 64),
            ("_", "after", 92),
            ("_source", "source", 0),
            ("_source", "flags", 32),
        ],
    )


def test_metal_structured_buffers_reproduce_hlsl_element_layout(tmp_path):
    metal = generate_metal("""
        struct Item
        {
            int2 P;
            bool B;
            bool2 H;
            float3 V;
        };

        RWStructuredBuffer<Item> items : register(u0);
        RWStructuredBuffer<float3> points : register(u1);
        RWStructuredBuffer<bool> flags : register(u2);

        [numthreads(64, 1, 1)]
        void Execute(uint3 ThreadIds : SV_DispatchThreadID)
        {
            items[ThreadIds.x].B = true;
            items[ThreadIds.x].H = bool2(true, false);
            items[ThreadIds.x].V = points[ThreadIds.x] * 2;
            flags[ThreadIds.x] = !flags[ThreadIds.x] && all(items[ThreadIds.x].H);
            points[ThreadIds.x] = float3(items[ThreadIds.x].P, items[ThreadIds.x].B ? 1 : 0);
        }
        """)

    assert (
        "    packed_int2 P;\n    uint B;\n    packed_uint2 H;\n    packed_float3 V;\n"
        in metal
    )
    assert "device packed_float3* points" in metal
    assert "device uint* flags" in metal
    assert "items[ThreadIds.x].H = uint2(bool2(true, false));" in metal
    assert "flags[ThreadIds.x] = !bool(flags[ThreadIds.x])" in metal
    assert "all(bool2(items[ThreadIds.x].H))" in metal
    assert "bool(items[ThreadIds.x].B) ? 1 : 0" in metal
    compile_metal_with_layout(
        metal,
        tmp_path,
        offsets=[("Item", "B", 8), ("Item", "H", 12), ("Item", "V", 20)],
        sizes=[("Item", 32)],
    )


def test_metal_keeps_natural_vectors_where_they_match_the_hlsl_layout(tmp_path):
    metal = generate_metal("""
        struct Pair
        {
            float4 A;
            float B;
        };

        cbuffer Scene : register(b0)
        {
            float4 offset;
            float4 padding[15];
        }

        cbuffer Tail : register(b1)
        {
            uint __x;
            float4 color;
            float3 direction;
        }

        StructuredBuffer<float4> colors : register(t0);
        RWStructuredBuffer<Pair> pairs : register(u0);
        RWStructuredBuffer<int2> cells : register(u1);

        [numthreads(64, 1, 1)]
        void Execute(uint3 ThreadIds : SV_DispatchThreadID)
        {
            pairs[ThreadIds.x].A = colors[ThreadIds.x] * offset + color;
            pairs[ThreadIds.x].B = direction.x + padding[ThreadIds.x].y;
            cells[ThreadIds.x] = int2(ThreadIds.xy) + int(__x);
        }
        """)

    # Same size and an aligned offset: the natural vector type.
    assert "    float4 offset;\n" in metal
    assert "const device float4* colors" in metal
    assert "device int2* cells" in metal
    # A natural float4 would raise the alignment of this constant buffer and
    # round its 44-byte size up to 48.
    assert "    packed_float4 color;\n" in metal
    assert "    packed_float3 direction;\n" in metal
    # Structured elements are four-byte aligned: Pair has a 20-byte stride.
    assert "    packed_float4 A;\n" in metal
    compile_metal_with_layout(
        metal,
        tmp_path,
        offsets=[
            ("Scene", "padding", 16),
            ("Tail", "color", 16),
            ("Tail", "direction", 32),
            ("Pair", "B", 16),
        ],
        sizes=[("Scene", 256), ("Tail", 44), ("Pair", 20)],
    )


def test_metal_passes_hlsl_layout_members_to_reference_parameters_through_temporaries(
    tmp_path,
):
    metal = generate_metal("""
        struct Item
        {
            float3 V;
            float W;
        };

        RWStructuredBuffer<Item> items : register(u0);

        void Scale(inout float3 value)
        {
            value *= 2;
        }

        [numthreads(64, 1, 1)]
        void Execute(uint3 ThreadIds : SV_DispatchThreadID)
        {
            Item item = items[ThreadIds.x];
            Scale(item.V);
            items[ThreadIds.x] = item;
        }
        """)

    assert "Scale(item.V);" not in metal
    compile_metal_with_layout(
        metal, tmp_path, offsets=[("Item", "W", 12)], sizes=[("Item", 16)]
    )


def test_metal_rejects_hlsl_layouts_it_cannot_reproduce():
    # The last element of an HLSL array is not padded to a register, so the
    # next member packs into it; Metal array elements cannot overlap it.
    with pytest.raises(ValueError, match="overlaps the Metal storage"):
        generate_metal("""
            cbuffer _ : register(b0) { float a[2]; float b; }
            RWStructuredBuffer<float> o : register(u0);
            [numthreads(1, 1, 1)]
            void main(uint3 id : SV_DispatchThreadID) { o[id.x] = a[id.x] + b; }
            """)

    with pytest.raises(ValueError, match="matrices in HLSL structured buffers"):
        generate_metal("""
            RWStructuredBuffer<float2x2> m : register(u0);
            [numthreads(1, 1, 1)]
            void main(uint3 id : SV_DispatchThreadID) { m[id.x] = m[id.x] * 2.0; }
            """)

    with pytest.raises(ValueError, match="different layouts"):
        generate_metal("""
            struct Pair { float3 a; float2 b; };
            cbuffer _ : register(b0) { Pair pair; }
            RWStructuredBuffer<Pair> pairs : register(u0);
            [numthreads(1, 1, 1)]
            void main(uint3 id : SV_DispatchThreadID) { pairs[id.x] = pair; }
            """)


def test_crossgl_buffers_without_a_layout_keep_the_metal_layout():
    metal = generate_metal_from_crossgl("""
        shader main {
            cbuffer Params {
                bool enabled;
                ivec3 offset;
                float scale;
            }
            compute {
                @ numthreads(1, 1, 1)
                void main(uvec3 id @ gl_GlobalInvocationID) @ stage_entry {
                    float value = enabled ? scale : 0.0;
                }
            }
        }
        """)

    assert "    bool enabled;\n    int3 offset;\n    float scale;\n" in metal
