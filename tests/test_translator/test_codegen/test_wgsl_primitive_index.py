"""WGSL output of the primitive index (``gl_PrimitiveID``, ``SV_PrimitiveID``, ``[[primitive_id]]``).

WGSL has ``@builtin(primitive_index)`` only as a ``u32`` fragment input, behind
``enable primitive_index;`` (WGSL sections 4.1.1 and 13.3.1.1.11).
"""

import shutil
import subprocess

import pytest

from crosstl.translator.codegen.wgsl_codegen import WGSLCodeGen
from crosstl.translator.codegen.wgsl_stage_io import WGSLStageIOUnsupportedError
from crosstl.translator.lexer import Lexer
from crosstl.translator.parser import Parser

HEADER = "// Generated by CrossGL for WebGPU WGSL\n\nenable primitive_index;\n\n"


def generate_wgsl(source):
    ast = Parser(Lexer(source).get_tokens()).parse()
    return WGSLCodeGen().generate(ast)


def validate_with_naga(tmp_path, code):
    naga = shutil.which("naga")
    if naga is None:
        pytest.skip("naga is not installed")
    path = tmp_path / "shader.wgsl"
    path.write_text(code, encoding="utf-8")
    result = subprocess.run(
        [naga, str(path)], capture_output=True, text=True, timeout=60
    )
    assert result.returncode == 0, result.stdout + result.stderr


def test_int_member_is_u32_and_read_as_i32(tmp_path):
    code = generate_wgsl("""
shader Probe {
    struct FragmentInput {
        vec2 uv;
        int pid @ gl_PrimitiveID;
    }
    struct FragmentOutput {
        vec4 color;
    }
    fragment {
        FragmentOutput main(FragmentInput input) {
            FragmentOutput output;
            int below = input.pid - 1;
            output.color = vec4(input.uv, float(input.pid), float(below));
            return output;
        }
    }
}
""")
    assert code.startswith(HEADER)
    assert code.count("enable primitive_index;") == 1
    assert "    @builtin(primitive_index) pid: u32,\n" in code
    assert "var below: i32 = (i32(input.pid) - 1);" in code
    assert "f32(i32(input.pid))" in code
    validate_with_naga(tmp_path, code)


def test_int_parameter_is_received_as_u32(tmp_path):
    code = generate_wgsl("""
shader Probe {
    fragment {
        vec4 main(vec2 uv, int pid @ gl_PrimitiveID) @ gl_FragColor {
            int below = pid - 1;
            return vec4(uv, float(below), 1.0);
        }
    }
}
""")
    assert code.startswith(HEADER)
    assert "@builtin(primitive_index) pid_primitive_index: u32)" in code
    assert "var pid: i32 = i32(pid_primitive_index);" in code
    validate_with_naga(tmp_path, code)


@pytest.mark.parametrize("semantic", ["SV_PrimitiveID", "primitive_id"])
def test_uint_hlsl_and_metal_spellings_stay_u32(tmp_path, semantic):
    code = generate_wgsl(f"""
shader Probe {{
    fragment {{
        vec4 main(vec4 color, uint primitive @ {semantic}) @ gl_FragColor {{
            return color * float(primitive & 1u);
        }}
    }}
}}
""")
    assert code.startswith(HEADER)
    assert "@builtin(primitive_index) primitive: u32)" in code
    assert "f32((primitive & 1u))" in code
    validate_with_naga(tmp_path, code)


def test_module_without_primitive_index_enables_nothing():
    code = generate_wgsl("""
shader Probe {
    fragment {
        vec4 main(vec4 color, uint index @ SV_SampleIndex) @ gl_FragColor {
            return color;
        }
    }
}
""")
    assert "enable" not in code


@pytest.mark.parametrize(
    "stage, declaration, match",
    [
        (
            "vertex",
            "vec4 main(vec3 p, uint pid @ SV_PrimitiveID) @ gl_Position "
            "{ return vec4(p, float(pid)); }",
            "vertex entry-point parameter 'pid'",
        ),
        (
            "compute",
            "layout(local_size_x = 1) in; void main(uint pid @ SV_PrimitiveID) { }",
            "compute entry-point parameter 'pid'",
        ),
        (
            "vertex",
            "Out main(vec3 p) { Out o; o.position = vec4(p, 1.0); o.pid = 1u; "
            "return o; }",
            "vertex output member Out.pid",
        ),
    ],
)
def test_primitive_index_outside_fragment_inputs_is_refused(stage, declaration, match):
    with pytest.raises(WGSLStageIOUnsupportedError, match=match):
        generate_wgsl(f"""
shader Probe {{
    struct Out {{
        vec4 position @ gl_Position;
        uint pid @ primitive_id;
    }}
    {stage} {{
        {declaration}
    }}
}}
""")


def test_non_integer_primitive_index_is_refused():
    with pytest.raises(
        WGSLStageIOUnsupportedError, match="FragmentInput.pid of type f32"
    ):
        generate_wgsl("""
shader Probe {
    struct FragmentInput {
        float pid @ SV_PrimitiveID;
    }
    fragment {
        vec4 main(FragmentInput input) @ gl_FragColor {
            return vec4(input.pid);
        }
    }
}
""")


def test_write_to_int_primitive_index_member_is_refused():
    with pytest.raises(
        WGSLStageIOUnsupportedError, match="cannot write member FragmentInput.pid"
    ):
        generate_wgsl("""
shader Probe {
    struct FragmentInput {
        int pid @ gl_PrimitiveID;
    }
    fragment {
        vec4 main(FragmentInput input) @ gl_FragColor {
            input.pid = input.pid + 1;
            return vec4(float(input.pid));
        }
    }
}
""")
