"""WGSL output writes CrossGL clip distances as the ``clip_distances`` built-in vertex output.

WGSL has user clip distances only as ``@builtin(clip_distances)`` of type ``array<f32, N>``, N from 1 to 8, on a
vertex shader output, in a module that enables ``clip_distances``. A ``float`` member is declared ``array<f32, 1>``
and accessed as element 0; a ``float[N]`` member keeps its type. Every output is validated with naga when it is
installed.
"""

import shutil
import subprocess

import pytest

import crosstl
from crosstl.translator.codegen.wgsl_stage_io import WGSLStageIOUnsupportedError


def program(member, body, fragment=""):
    return f"""shader Probe {{
    struct VertexOutput {{
        vec4 position @ gl_Position;
        {member}
    }}
    vertex {{
        VertexOutput main(vec4 p @ POSITION) {{
{body}
        }}
    }}
{fragment}
}}
"""


def translate(tmp_path, source):
    path = tmp_path / "probe.cgl"
    path.write_text(source)
    output = crosstl.translate(str(path), backend="wgsl", format_output=False)
    if shutil.which("naga"):
        (tmp_path / "out.wgsl").write_text(output)
        checked = subprocess.run(
            ["naga", "out.wgsl"], cwd=tmp_path, capture_output=True, text=True
        )
        assert checked.returncode == 0, checked.stdout + checked.stderr
    return output


@pytest.mark.parametrize(
    "semantic", ["gl_ClipDistance", "SV_ClipDistance", "SV_ClipDistance0"]
)
def test_a_float_member_is_a_one_element_clip_distance_array(tmp_path, semantic):
    wgsl = translate(
        tmp_path,
        program(
            f"float clip @ {semantic};",
            """            VertexOutput output;
            output.position = p;
            output.clip = p.x;
            output.clip = output.clip * 2.0 + 1.0;
            return output;""",
        ),
    )
    assert wgsl.startswith(
        "// Generated by CrossGL for WebGPU WGSL\n\nenable clip_distances;\n"
    )
    assert "@builtin(clip_distances) clip: array<f32, 1>," in wgsl
    assert "output.clip[0] = p.x;" in wgsl
    assert "output.clip[0] = ((output.clip[0] * 2.0) + 1.0);" in wgsl


def test_a_float_array_member_keeps_its_elements(tmp_path):
    wgsl = translate(
        tmp_path,
        program(
            "float clip[3] @ gl_ClipDistance;",
            """            VertexOutput output;
            output.position = p;
            for (int k = 0; k < 3; k++) {
                output.clip[k] = p[k];
            }
            return output;""",
        ),
    )
    assert "enable clip_distances;" in wgsl
    assert "@builtin(clip_distances) clip: array<f32, 3>," in wgsl
    assert "output.clip[k] = p[k];" in wgsl
    # A built-in array is not split into one located member per element.
    assert "clip_0" not in wgsl


@pytest.mark.parametrize(
    "construction, expected",
    [
        ("VertexOutput(p, p.x)", "VertexOutput(p, array<f32, 1>(p.x))"),
        (
            "VertexOutput { position: p, clip: p.x }",
            "VertexOutput(p, array<f32, 1>(p.x))",
        ),
        ("{p}", "VertexOutput(p, array<f32, 1>())"),
    ],
)
def test_a_constructed_float_member_becomes_its_array(tmp_path, construction, expected):
    wgsl = translate(
        tmp_path,
        program(
            "float clip @ gl_ClipDistance;",
            f"""            VertexOutput output = {construction};
            return output;""",
        ),
    )
    assert f"var output: VertexOutput = {expected};" in wgsl


def test_a_helper_reads_the_float_member_as_element_zero(tmp_path):
    source = program(
        "float clip @ gl_ClipDistance;",
        """            VertexOutput output;
            output.position = p;
            output.clip = p.y;
            output.position.w = clipOf(output);
            return output;""",
    ).replace(
        "    vertex {",
        "    float clipOf(VertexOutput o) {\n        return o.clip;\n    }\n    vertex {",
    )
    wgsl = translate(tmp_path, source)
    assert "return o.clip[0];" in wgsl


def test_programs_without_clip_distances_enable_nothing(tmp_path):
    wgsl = translate(
        tmp_path,
        program(
            "float depth;",
            """            VertexOutput output;
            output.position = p;
            output.depth = p.z;
            return output;""",
        ),
    )
    assert "enable" not in wgsl


@pytest.mark.parametrize(
    "member, message",
    [
        ("vec4 clip @ gl_ClipDistance;", "of type vec4<f32> to clip_distances"),
        ("float clip[9] @ gl_ClipDistance;", "with N from 1 to 8"),
        ("int clip @ gl_ClipDistance;", "of type i32 to clip_distances"),
    ],
)
def test_other_clip_distance_types_are_refused(tmp_path, member, message):
    with pytest.raises(WGSLStageIOUnsupportedError, match=message):
        translate(
            tmp_path,
            program(
                member, "            VertexOutput output;\n            return output;"
            ),
        )


def test_a_fragment_input_clip_distance_is_refused(tmp_path):
    fragment = """    fragment {
        vec4 main(VertexOutput input) @ gl_FragColor {
            return input.position;
        }
    }"""
    source = program(
        "float clip @ gl_ClipDistance;",
        "            VertexOutput output;\n            return output;",
        fragment,
    )
    with pytest.raises(
        WGSLStageIOUnsupportedError,
        match="fragment input member VertexOutput.clip to clip_distances",
    ):
        translate(tmp_path, source)


def test_a_fragment_parameter_clip_distance_is_refused(tmp_path):
    source = """shader S {
    fragment {
        vec4 main(vec4 color, float clip @ SV_ClipDistance0) @ gl_FragColor {
            return color;
        }
    }
}
"""
    with pytest.raises(
        WGSLStageIOUnsupportedError,
        match="fragment entry-point parameter 'clip' to clip_distances",
    ):
        translate(tmp_path, source)


def test_a_second_hlsl_clip_register_stays_refused(tmp_path):
    with pytest.raises(WGSLStageIOUnsupportedError, match="SV_ClipDistance1"):
        translate(
            tmp_path,
            program(
                "float clip @ SV_ClipDistance1;",
                "            VertexOutput output;\n            return output;",
            ),
        )
